#!/usr/bin/env python3
"""Build qml/org/theone/keyboard/Words.js from data/en_50k.txt.

data/en_50k.txt is the English 50k list from hermitdave/FrequencyWords
(OpenSubtitles 2018 counts, CC BY-SA 4.0). The subtitles tokenizer splits
contractions ("don't" -> "don" + "'t"), so this script puts them back together,
drops the fragments and the apostrophe-less typos ("dont", "im") that would
otherwise stop autocorrect, and keeps words on data/blocklist.txt out of the
suggestions (they are still known, so they are never "corrected").

    python3 scripts/build_words.py
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "en_50k.txt")
BLOCK = os.path.join(ROOT, "data", "blocklist.txt")
OUT = os.path.join(ROOT, "qml", "org", "theone", "keyboard", "Words.js")

WORD = re.compile(r"^[a-zà-öø-ÿ]+$")

counts = {}
for line in open(SRC, encoding="utf-8"):
    w, c = line.split()
    counts[w] = counts.get(w, 0) + int(c)

out = {}
for w, c in counts.items():
    if WORD.match(w) and (len(w) > 1 or w in ("a", "i")):
        out[w] = c

# n't: the stem fragment ("don", "isn") only ever occurs in the contraction.
NT = ["don", "doesn", "didn", "isn", "wasn", "couldn", "wouldn", "shouldn", "haven",
      "hasn", "hadn", "aren", "weren", "ain", "mustn", "needn"]
used_t = 0
for stem in NT:
    c = counts.get(stem, 0)
    out.pop(stem, None)
    out[stem + "'t"] = c
    used_t += c
rest_t = max(counts.get("'t", 0) - used_t, 0)
out["can't"] = int(rest_t * 0.7)
out["won't"] = int(rest_t * 0.3)

out["i'm"] = counts.get("'m", 0)

CLITICS = {
    "'s": (["it", "that", "what", "he", "she", "there", "let", "here", "who", "where",
            "how", "everything", "nothing", "something", "someone", "everyone"], 0.25),
    "'re": (["you", "we", "they", "who", "what"], 0.2),
    "'ve": (["i", "you", "we", "they", "would", "could", "should", "might", "must", "who"], 0.06),
    "'ll": (["i", "you", "we", "he", "she", "they", "it", "that", "there", "who"], 0.08),
    "'d": (["i", "you", "he", "she", "we", "they", "it", "that", "who"], 0.05),
}
for clitic, (bases, share) in CLITICS.items():
    for b in bases:
        out[b + clitic] = int(counts.get(b, 0) * share)
out["y'all"] = 5000
out["o'clock"] = counts.get("clock", 0) // 2

# Fragments left behind by the split, and apostrophe-less spellings of contractions
# that are typos rather than words ("dont", "youre"), so autocorrect can fix them.
for frag in ["t", "s", "m", "ll", "ve", "re", "d", "o", "y"]:
    out.pop(frag, None)
REAL = {"well", "were", "its", "lets", "hell", "shell", "wed", "ill", "id", "shed"}
for w in list(out):
    if "'" in w:
        bare = w.replace("'", "")
        if bare in out and bare not in REAL:
            del out[bare]

blocked = set()
if os.path.exists(BLOCK):
    for line in open(BLOCK, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            blocked.add(line)

ranked = sorted(out.items(), key=lambda kv: (-kv[1], kv[0]))
shown = [w for w, c in ranked if w not in blocked and c > 0]
hidden = [w for w, c in ranked if w in blocked]

with open(OUT, "w", encoding="utf-8") as f:
    f.write(".pragma library\n")
    f.write("// Generated by scripts/build_words.py from data/en_50k.txt. Do not edit.\n")
    f.write("// Word list: hermitdave/FrequencyWords (OpenSubtitles 2018), CC BY-SA 4.0.\n")
    f.write("// WORDS is ordered from most to least common. HIDDEN words are known but\n")
    f.write("// never suggested.\n")
    f.write('var WORDS = "%s"\n' % " ".join(shown))
    f.write('var HIDDEN = "%s"\n' % " ".join(hidden))
    f.write("// The same words in alphabetical order, for prefix lookups.\n")
    f.write('var SORTED = "%s"\n' % " ".join(sorted(shown)))

print("%d words, %d hidden, %d KB" % (len(shown), len(hidden), os.path.getsize(OUT) // 1024))
