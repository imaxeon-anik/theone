#!/usr/bin/env python3
"""Build the emoji search words from Unicode CLDR.

For every emoji on theOne's emoji page (Layouts.js), takes its English name and
keywords from CLDR (common/annotations/en.xml and common/annotationsDerived/en.xml,
Unicode License v3) and writes qml/org/theone/keyboard/EmojiNames.js.

    python3 scripts/build_emoji_names.py
"""
import html
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYOUTS = os.path.join(ROOT, "qml", "org", "theone", "keyboard", "Layouts.js")
OUT = os.path.join(ROOT, "qml", "org", "theone", "keyboard", "EmojiNames.js")
RELEASE = "release-49"
BASE = "https://raw.githubusercontent.com/unicode-org/cldr/%s/" % RELEASE
FILES = ["common/annotations/en.xml", "common/annotationsDerived/en.xml"]

opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def fetch(path):
    return opener.open(BASE + path, timeout=60).read().decode("utf-8")


# cp (without FE0F) -> {"name": ..., "words": [...]}
cldr = {}
for path in FILES:
    for attrs, text in re.findall(r"<annotation ([^>]*)>([^<]*)</annotation>", fetch(path)):
        cp = html.unescape(re.search(r'cp="([^"]*)"', attrs).group(1))
        entry = cldr.setdefault(cp, {"name": "", "words": []})
        text = html.unescape(text).strip()
        if 'type="tts"' in attrs:
            entry["name"] = text
        else:
            entry["words"] = [w.strip() for w in text.split("|") if w.strip()]

# The CLDR LICENSE file opens with terms for the LDML specification text; the data
# files are under the Unicode License v3 that follows it.
licence = fetch("LICENSE")
copyright = re.search(r"Copyright ©[^\n]*Unicode, Inc\.", licence).group(0)
licence = "UNICODE LICENSE V3\n\n" + copyright + "\n\n" + licence[licence.index("NOTICE TO USER"):]

src = open(LAYOUTS, encoding="utf-8").read()
emoji = []
for block in re.findall(r'list: "([^"]*)"', src):
    for e in block.split(" "):
        if e and e not in emoji:
            emoji.append(e)

lines, missing = [], []
for e in emoji:
    entry = cldr.get(e.replace("️", ""))
    if not entry or not entry["name"]:
        missing.append(e)
        continue
    # The name first (it ranks highest), then the keywords that add something.
    words = [entry["name"].lower()]
    for w in entry["words"]:
        w = w.lower()
        if w not in words:
            words.append(w)
    lines.append('    "%s": "%s"' % (e, "|".join(words).replace('"', '\\"')))

with open(OUT, "w", encoding="utf-8") as f:
    f.write(".pragma library\n")
    f.write("// Generated by scripts/build_emoji_names.py from Unicode CLDR %s\n" % RELEASE)
    f.write("// (common/annotations/en.xml, common/annotationsDerived/en.xml). Do not edit.\n")
    f.write("// emoji -> \"name|keyword|keyword...\", lower case. Licence of the data:\n//\n")
    for l in licence.strip().splitlines():
        f.write(("// " + l).rstrip() + "\n")
    f.write("\nvar NAMES = {\n")
    f.write(",\n".join(lines))
    f.write("\n}\n")

print("%d emoji, %d without a CLDR name: %s" % (len(emoji), len(missing), " ".join(missing)))
sys.exit(1 if missing else 0)
